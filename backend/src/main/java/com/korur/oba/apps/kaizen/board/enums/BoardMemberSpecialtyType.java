package com.korur.oba.apps.kaizen.board.enums;

/**
 * Defines the professional specialty of a board member.
 * <p>
 * A member can hold multiple specialties on a single board.
 */
public enum BoardMemberSpecialtyType {

    // Software development and programming.
    DEVELOPER,

    // Security analysis, vulnerability assessment, and threat mitigation.
    CYBERSECURITY_SPECIALIST,

    // Product vision, backlog prioritization, and stakeholder communication.
    PRODUCT_OWNER,

    // Agile facilitation, sprint planning, and team impediment removal.
    SCRUM_MASTER,

    // Quality assurance, testing strategy, and defect management.
    QA_ENGINEER,

    // Infrastructure, CI/CD pipelines, and deployment automation.
    DEVOPS_ENGINEER,

    // UI/UX design, visual design, and user research.
    DESIGNER,

    // System architecture, technical strategy, and cross-cutting concerns.
    ARCHITECT
}
