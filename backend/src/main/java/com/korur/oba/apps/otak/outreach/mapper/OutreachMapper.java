package com.korur.oba.apps.otak.outreach.mapper;

// 1. Framework-level

// 2. Third-party
import org.mapstruct.InjectionStrategy;
import org.mapstruct.Mapper;
import org.mapstruct.Mapping;
import org.mapstruct.MappingTarget;

// 3. Java SDK

// 4. Internal
import com.korur.oba.apps.otak.contact.dto.response.ContactListResponse;
import com.korur.oba.apps.otak.contact.entity.Contact;
import com.korur.oba.apps.otak.mail.entity.Mail;
import com.korur.oba.apps.otak.outreach.dto.request.OutreachCreateRequest;
import com.korur.oba.apps.otak.outreach.dto.request.OutreachUpdateRequest;
import com.korur.oba.apps.otak.outreach.dto.response.OutreachContactResponse;
import com.korur.oba.apps.otak.outreach.dto.response.OutreachDetailResponse;
import com.korur.oba.apps.otak.outreach.dto.response.OutreachListResponse;
import com.korur.oba.apps.otak.outreach.dto.response.OutreachMailResponse;
import com.korur.oba.apps.otak.outreach.entity.Outreach;

/**
 * Maps outreach entities to DTOs and requests to entities. An outreach holds only plain ids, so
 * the contact, the sender address and the mail are looked up by the query service and passed in; this mapper never reads anything itself.
 *
 * Every field that the server owns is ignored on the request-to-entity mappings: the id
 * and timestamps, the organization (taken from the checked request header, never from a
 * body), the status, the mail link and the send columns. The type is mapped on create only. A client therefore
 * cannot set an outreach to SENT, move it to another organization or point it at another
 * mail through a request.
 *
 * Used by {@link com.korur.oba.apps.otak.outreach.service.impl.OutreachServiceImpl} for writes and by
 * {@link com.korur.oba.apps.otak.outreach.service.impl.OutreachQueryServiceImpl} for responses. Generated by
 * MapStruct as a Spring bean with constructor injection.
 */
@Mapper(componentModel = "spring", injectionStrategy = InjectionStrategy.CONSTRUCTOR)
public interface OutreachMapper {

    /**
     * Maps a create request to a new entity: the relation, the contact, the title and the
     * type. The service then sets the trimmed title, the organization, the status
     * {@link com.korur.oba.apps.otak.outreach.enums.OutreachStatus#DRAFT} and the mail link;
     * the send columns stay empty until a send claims the outreach.
     *
     * Called by {@link com.korur.oba.apps.otak.outreach.service.impl.OutreachServiceImpl#create}.
     *
     * @param request the validated create request
     * @return a new, unsaved outreach
     */
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "organizationId", ignore = true)
    @Mapping(target = "status", ignore = true)
    @Mapping(target = "mailId", ignore = true)
    @Mapping(target = "mailSenderId", ignore = true)
    @Mapping(target = "sentTo", ignore = true)
    @Mapping(target = "sentAt", ignore = true)
    Outreach toEntity(OutreachCreateRequest request);

    /**
     * Writes the contact and the title of an update request onto the outreach. The mail
     * lives in the outreach's own mail and is written through the mail service. The type is
     * fixed after create and not in the request. The relation is ignored as well: the mail and its attachments belong to that relation, so it is
     * fixed after create. A null contact in the request is not possible,
     * because the update request requires it.
     *
     * Called by {@link com.korur.oba.apps.otak.outreach.service.impl.OutreachServiceImpl#update}, on an
     * outreach read with the row lock.
     *
     * @param outreach the stored outreach, changed in place
     * @param request  the validated update request
     */
    @Mapping(target = "id", ignore = true)
    @Mapping(target = "createdAt", ignore = true)
    @Mapping(target = "updatedAt", ignore = true)
    @Mapping(target = "organizationId", ignore = true)
    @Mapping(target = "relationId", ignore = true)
    @Mapping(target = "type", ignore = true)
    @Mapping(target = "status", ignore = true)
    @Mapping(target = "mailId", ignore = true)
    @Mapping(target = "mailSenderId", ignore = true)
    @Mapping(target = "sentTo", ignore = true)
    @Mapping(target = "sentAt", ignore = true)
    void updateEntity(@MappingTarget Outreach outreach, OutreachUpdateRequest request);

    /**
     * Maps a stored contact to the contact of an outreach, for the detail response.
     *
     * Called by {@link com.korur.oba.apps.otak.outreach.service.impl.OutreachQueryServiceImpl#get}.
     *
     * @param contact the contact entity, read within the outreach's relation
     * @return the contact as the outreach shows it
     */
    OutreachContactResponse toContactResponse(Contact contact);

    /**
     * Maps a listed contact to the contact of an outreach, for the list response, where
     * the contacts of a page are read in bulk as list items.
     *
     * Called by the contact-reading helper of
     * {@link com.korur.oba.apps.otak.outreach.service.impl.OutreachQueryServiceImpl#list}.
     *
     * @param contact the contact list item
     * @return the contact as the outreach shows it
     */
    OutreachContactResponse toContactResponse(ContactListResponse contact);

    /**
     * Maps an outreach to a list item. The id and the timestamps are taken from the
     * outreach explicitly, so the contact's own id never takes the outreach's place.
     *
     * Called by {@link com.korur.oba.apps.otak.outreach.service.impl.OutreachQueryServiceImpl#list}.
     *
     * @param outreach          the outreach
     * @param contact           its contact, or null when the contact was deleted
     * @param mailSenderAddress the address of its mail sender, or null
     * @return the list item
     */
    @Mapping(target = "id", source = "outreach.id")
    @Mapping(target = "contact", source = "contact")
    @Mapping(target = "updatedAt", source = "outreach.updatedAt")
    @Mapping(target = "createdAt", source = "outreach.createdAt")
    OutreachListResponse toListResponse(Outreach outreach, OutreachContactResponse contact, String mailSenderAddress);

    /**
     * Maps an outreach to the detail response. The id and the timestamps are taken from the
     * outreach explicitly, so the contact's own id never takes the outreach's place.
     *
     * Called by {@link com.korur.oba.apps.otak.outreach.service.impl.OutreachQueryServiceImpl#get}, which
     * every write of {@link com.korur.oba.apps.otak.outreach.service.impl.OutreachServiceImpl} answers with.
     *
     * @param outreach          the outreach
     * @param contact           its contact, or null when the contact was deleted
     * @param mailSenderAddress the address of its mail sender, or null
     * @param mail              its mail, or null for a WHATSAPP or CALL outreach
     * @return the detail response
     */
    @Mapping(target = "id", source = "outreach.id")
    @Mapping(target = "contact", source = "contact")
    @Mapping(target = "mail", source = "mail")
    @Mapping(target = "updatedAt", source = "outreach.updatedAt")
    @Mapping(target = "createdAt", source = "outreach.createdAt")
    OutreachDetailResponse toDetailResponse(Outreach outreach, OutreachContactResponse contact,
                                            String mailSenderAddress, OutreachMailResponse mail);

    /**
     * Maps the outreach's mail to the mail of the detail response: its id, template link,
     * subject, body and language. Returns null for a null mail, which a WHATSAPP or CALL
     * outreach has; the query service skips the call then anyway.
     *
     * Called by {@link com.korur.oba.apps.otak.outreach.service.impl.OutreachQueryServiceImpl#get}.
     *
     * @param mail the mail of the outreach, or null
     * @return the mail of the outreach as the detail response shows it, or null
     */
    OutreachMailResponse toMailResponse(Mail mail);
}
