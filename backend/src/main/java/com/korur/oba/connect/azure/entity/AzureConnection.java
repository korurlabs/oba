package com.korur.oba.connect.azure.entity;

// 1. Framework-level

// 2. Third-party
import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.PrePersist;
import jakarta.persistence.Table;
import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Getter;
import lombok.NoArgsConstructor;
import lombok.Setter;
import lombok.experimental.SuperBuilder;
import org.hibernate.annotations.JdbcType;
import org.hibernate.dialect.PostgreSQLEnumJdbcType;

// 3. Java SDK
import java.time.Instant;
import java.util.UUID;

// 4. Internal
import com.korur.oba.connect.azure.constant.AzureConnectionConstant;
import com.korur.oba.connect.azure.enums.AzureConnectionStatus;
import com.korur.oba.dojo.entity.BaseEntity;

/**
 * An organization's link to an Azure identity (a user-assigned managed identity or an app
 * registration) in the organization's own tenant, through which Oba reads Azure Resource Manager.
 *
 * It holds no credential. Azure trusts the subject because the organization created a federated
 * credential for it on that identity, and Oba signs an assertion for the subject only for this row,
 * loaded by its id and organization. The subject is stored rather than derived on each use, so a
 * later change of its format never breaks a federated credential that exists.
 *
 * The organization's rows are removed with the organization; the subscriptions of a connection are
 * removed with the connection ({@link AzureConnectionSubscription}).
 */
@Entity
@Table(name = "azure_connections", schema = "shrine")
@SuperBuilder
@Getter
@Setter
@AllArgsConstructor
@NoArgsConstructor
public class AzureConnection extends BaseEntity {

    // -------------Atts-----------//

    /**
     * Name the admin gave the connection, unique within the organization.
     */
    @Column(name = "name", length = 255, nullable = false)
    private String name;

    /**
     * Directory (tenant) id of the organization's Entra ID tenant that holds the identity.
     */
    @Column(name = "tenant_id", nullable = false)
    private UUID tenantId;

    /**
     * Client id of the identity; null until the admin has created the identity, which needs the
     * subject this row shows first. A check refuses to run without it.
     */
    @Column(name = "client_id", nullable = true)
    private UUID clientId;

    /**
     * Subject of the assertions Oba signs for this connection, set once by {@link #assignSubject}
     * from the organization and the new id and never changed, also when the name, tenant or client
     * id change. Unique across all organizations, so one federated credential can only ever serve
     * one connection.
     */
    @Column(name = "subject", length = 600, nullable = false, unique = true, updatable = false)
    private String subject;

    /**
     * Last time a check succeeded; null before the first success and after an identity change.
     */
    @Column(name = "last_verified_at", columnDefinition = "TIMESTAMP WITH TIME ZONE", nullable = true)
    private Instant lastVerifiedAt;

    /**
     * Error code of the latest failed check, such as an AADSTS code; null after a success. Never
     * the raw Entra or Azure Resource Manager message.
     */
    @Column(name = "last_error", length = 1000, nullable = true)
    private String lastError;

    @Builder.Default
    @Enumerated(EnumType.STRING)
    @JdbcType(PostgreSQLEnumJdbcType.class)
    @Column(name = "status", nullable = false)
    private AzureConnectionStatus status = AzureConnectionStatus.PENDING;

    /**
     * Organization that owns the connection, set once on create from the request's checked
     * organization and never from a body.
     */
    @Column(name = "organization_id", nullable = false, updatable = false)
    private UUID organizationId;

    /**
     * User who created the connection; cleared when that user is deleted, the connection stays.
     */
    @Column(name = "created_by_id", nullable = true, updatable = false)
    private UUID createdById;

    // -------------Lifecycle-----------//

    /**
     * Sets the subject when the row is first persisted. The id is generated by then, and Hibernate
     * takes the inserted values at persist, so a subject set after save would reach the database
     * only as a later update and the insert would break the not-null column.
     */
    @PrePersist
    void assignSubject() {
        if (subject == null) {
            subject = String.format(AzureConnectionConstant.SUBJECT_FORMAT, organizationId, getId());
        }
    }
}
